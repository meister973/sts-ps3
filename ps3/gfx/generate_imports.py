#!/usr/bin/env python3
"""Keep PS3 declarations aligned with VitaGL20's TeaVM import ABI.

Java passes int32 booleans and IDs, floats, and pointer-sized Address values.
This is an application boundary, not a claim to implement the complete GLES ABI.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[2]
java = (root/'backend/src/main/java/com/stsvita/backend/VitaGL20.java').read_text()
ctype = {'void':'void', 'int':'int', 'boolean':'int', 'float':'float', 'Address':'void *'}
imports = []
for name, ret, args in re.findall(r'@Import\(name = "([^"]+)"\)\s+private static native (\w+) \w+\((.*?)\);', java, re.S):
    if not name.startswith('gl'):
        continue
    params = []
    for arg in args.split(',') if args.strip() else []:
        typ, param = arg.strip().split()
        params.append(ctype[typ] + ' ' + param)
    imports.append((name, ctype[ret], ', '.join(params) or 'void'))
header = '''/* Generated by generate_imports.py from the TeaVM @Import declarations. */
#ifndef STSV_PS3_GL_IMPORTS_H
#define STSV_PS3_GL_IMPORTS_H
#include <stddef.h>
#include <stdint.h>
void stsv_gfx_init(void);
void stsv_swap_buffers(void);
void stsv_set_vsync(int on);
int stsv_is_host_harness(void);
int stsv_gfx_width(void);
int stsv_gfx_height(void);
int stsv_gfx_dump_frame(const char *path);
'''
for name, ret, args in imports:
    header += f'{ret} {name}({args});\n'
header += '#endif\n'
(root/'ps3/gfx/ps3_gl.h').write_text(header)
# Unsupported entry points explicitly set GL_INVALID_OPERATION and log once.
implemented = (root/'ps3/gfx/ps3_gl.c').read_text() if (root/'ps3/gfx/ps3_gl.c').exists() else ''
fallback = '/* Generated unsupported imports: fail visibly rather than report success. */\n#include "ps3_gl.h"\nextern void stsv_gl_unsupported(const char *);\n'
for name, ret, args in imports:
    if re.search(r'\b'+name+r'\s*\(', implemented):
        continue
    unused = ''.join(f'(void){a.strip().split()[-1]};' for a in args.split(',')) if args != 'void' else ''
    fallback += f'{ret} {name}({args}) {{ {unused} stsv_gl_unsupported("{name}");'
    if ret != 'void':
        fallback += ' return 0;'
    fallback += ' }\n'
(root/'ps3/gfx/unsupported_gl.c').write_text(fallback)
print(f'{len(imports)} GL boundary declarations generated')
