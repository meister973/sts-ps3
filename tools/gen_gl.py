#!/usr/bin/env python3
"""Generate VitaGL20.java: libGDX 1.9.5 GL20 implemented via TeaVM @Import
calls straight into the platform's GL symbols (libGL on host, vitaGL on
Vita — same names). Buffer params cross as position-adjusted addresses,
String params as NUL-terminated UTF-8. A few string-returning functions are
emitted from hand-written templates."""

import re
import subprocess

GDX_JAR = "gdx-1.9.5.jar"
OUT = "VitaGL20.java"

HAND_WRITTEN = {
    "glGetString", "glGetShaderInfoLog", "glGetProgramInfoLog",
    "glGetActiveAttrib", "glGetActiveUniform", "glShaderSource",
}

# gdx int params that are pointers in the C signature (VBO/IBO offsets)
INT_AS_POINTER = {
    ("glVertexAttribPointer", 5),  # (indx, size, type, normalized, stride, int ptr)
    ("glDrawElements", 3),         # (mode, count, type, int indices)
}

# libGDX GL20 convenience methods that are NOT real GL entry points (the real
# GL API only has the plural glGen*/glDelete* taking a count + buffer). These
# route to glue wrappers (gl_common_glue.c) instead of a same-named GL symbol.
NAME_OVERRIDE = {
    "glGenTexture": "stsv_gl_gen_texture",
    "glDeleteTexture": "stsv_gl_delete_texture",
    "glGenBuffer": "stsv_gl_gen_buffer",
    "glDeleteBuffer": "stsv_gl_delete_buffer",
    "glGenFramebuffer": "stsv_gl_gen_framebuffer",
    "glDeleteFramebuffer": "stsv_gl_delete_framebuffer",
    "glGenRenderbuffer": "stsv_gl_gen_renderbuffer",
    "glDeleteRenderbuffer": "stsv_gl_delete_renderbuffer",
}

BUFFER_TYPES = {"java.nio.Buffer", "java.nio.ByteBuffer", "java.nio.FloatBuffer",
                "java.nio.IntBuffer", "java.nio.ShortBuffer", "java.nio.DoubleBuffer",
                "java.nio.LongBuffer"}

PRIM = {"int": "int", "float": "float", "boolean": "boolean", "long": "long",
        "void": "void", "byte": "byte", "short": "short", "double": "double"}


def methods():
    out = subprocess.run(["javap", "-classpath", GDX_JAR,
                          "com.badlogic.gdx.graphics.GL20"],
                         capture_output=True, text=True, check=True).stdout
    ms = []
    for line in out.splitlines():
        m = re.match(r"\s*public abstract ([\w.$\[\]]+) (\w+)\((.*)\);", line.strip())
        if not m:
            continue
        ret, name, params = m.groups()
        plist = [p.strip() for p in params.split(",")] if params else []
        ms.append((ret, name, plist))
    return ms


def native_type(t):
    if t in BUFFER_TYPES or t == "java.lang.String":
        return "Address"
    return PRIM[t]


def emit():
    ms = methods()
    lines = ["""package com.stsvita.backend;

import com.badlogic.gdx.graphics.GL20;
import java.nio.Buffer;
import java.nio.ByteBuffer;
import java.nio.FloatBuffer;
import java.nio.IntBuffer;
import java.nio.ShortBuffer;
import org.teavm.interop.Address;
import org.teavm.interop.Import;
import org.teavm.interop.c.Include;

/**
 * GENERATED by tools/gen_gl.py from libGDX 1.9.5's GL20 — regenerate rather
 * than editing the generated section. Calls land directly on the platform's
 * GL exports (libGL on the host harness, vitaGL on Vita) via TeaVM @Import;
 * stsv_gl.h supplies the prototypes per platform. Buffers must be direct
 * (see Buffers); their position is honored as the data offset, matching
 * desktop-GL semantics.
 */
@Include("stsv_gl.h")
public class VitaGL20 implements GL20 {
    private static void putInt(Buffer buffer, int value) {
        if (buffer == null) {
            return;
        }
        if (buffer instanceof IntBuffer) {
            IntBuffer b = (IntBuffer) buffer;
            b.put(b.position(), value);
        } else if (buffer instanceof ByteBuffer) {
            ByteBuffer b = (ByteBuffer) buffer;
            b.putInt(b.position(), value);
        } else {
            throw new IllegalArgumentException("expected IntBuffer or ByteBuffer: " + buffer);
        }
    }

"""]
    n_gen = 0
    emitted_natives = set()
    # Typed-buffer element types for the bounce-array path below.
    TBUF = {"java.nio.IntBuffer": "int", "java.nio.FloatBuffer": "float",
            "java.nio.ShortBuffer": "short"}
    for ret, name, plist in ms:
        if name in HAND_WRITTEN:
            continue
        n_gen += 1
        sig = ", ".join(f"{simple(t)} p{i}" for i, t in enumerate(plist))

        # Typed-buffer bounce: libGDX (ShaderProgram, GLFrameBuffer) hands some
        # glGet*/glGen*/glDelete* a ByteBuffer.allocateDirect(...).asIntBuffer()
        # — a native buffer whose array() throws and whose malloc address we
        # can't reach (TeaVM prunes the internal address interface). So we
        # bounce through a heap array (Address.ofData works on arrays) and
        # move data across the java.nio API with get()/put(), which works for
        # any buffer backing. Only concrete typed buffers as the LAST param.
        last = plist[-1] if plist else None
        if (last in TBUF
                and all(t == "int" for t in plist[:-1])
                and (name.startswith("glGet") or name.startswith("glGen")
                     or name.startswith("glDelete"))):
            elem = TBUF[last]
            bi = len(plist) - 1
            is_input = name.startswith("glDelete")
            # element count: glGen/glDelete use the leading int n; glGet uses
            # the buffer's remaining().
            count = "p0" if (name.startswith("glGen") or name.startswith("glDelete")) \
                else f"p{bi}.remaining()"
            head = ", ".join(f"p{i}" for i in range(bi))
            lines.append("    @Override")
            lines.append(f"    public void {name}({sig}) {{")
            lines.append(f"        int __n = {count};")
            lines.append(f"        {elem}[] __t = new {elem}[__n];")
            if is_input:
                lines.append(f"        for (int __i = 0; __i < __n; __i++) "
                             f"__t[__i] = p{bi}.get(p{bi}.position() + __i);")
            call_args = (head + ", " if head else "") + "Address.ofData(__t)"
            lines.append(f"        n{name}({call_args});")
            if not is_input:
                lines.append(f"        for (int __i = 0; __i < __n; __i++) "
                             f"p{bi}.put(p{bi}.position() + __i, __t[__i]);")
            lines.append("    }")
            lines.append("")
            key = (name, "bounce")
            if key not in emitted_natives:
                emitted_natives.add(key)
                nsig = ", ".join(
                    ([f"{PRIM[t]} p{i}" for i, t in enumerate(plist[:bi])]) + ["Address p" + str(bi)])
                lines.append(f'    @Import(name = "{name}")')
                lines.append(f"    private static native void n{name}({nsig});")
                lines.append("")
            continue

        # wrapper
        lines.append("    @Override")
        lines.append(f"    public {simple(ret)} {name}({sig}) {{")
        conv = []
        args = []
        fused_offset = None
        for i, t in enumerate(plist):
            if i == fused_offset:
                continue  # consumed by the preceding array param
            if (name, i) in INT_AS_POINTER and t == "int":
                args.append(f"Address.fromInt(p{i})")
            elif t.endswith("[]"):
                # gdx array variants are always (T[] value, int offset):
                # the C call takes a single pointer &value[offset]
                assert i + 1 == len(plist) - 1 and plist[i + 1] == "int", (name, plist)
                fused_offset = i + 1
                args.append(f"Address.ofData(p{i}).add(p{i + 1} << 2)")
            elif t in BUFFER_TYPES:
                args.append(f"Buffers.addr(p{i})")
            elif t == "java.lang.String":
                conv.append(f"        byte[] c{i} = CStrings.toC(p{i});")
                args.append(f"Address.ofData(c{i})")
            else:
                args.append(f"p{i}")
        lines.extend(conv)
        call = f"n{name}({', '.join(args)})"
        lines.append(f"        {'return ' if ret != 'void' else ''}{call};")
        lines.append("    }")
        lines.append("")
        # native (dedupe: Buffer and array/offset variants erase identically)
        nsig = []
        skip = -1
        for i, t in enumerate(plist):
            if i == skip:
                continue
            if t.endswith("[]"):
                skip = i + 1
                nsig.append(f"Address p{i}")
            elif (name, i) in INT_AS_POINTER or t in BUFFER_TYPES or t == "java.lang.String":
                nsig.append(f"Address p{i}")
            else:
                nsig.append(f"{PRIM[t]} p{i}")
        key = (name, tuple(s.split()[0] for s in nsig))
        if key not in emitted_natives:
            emitted_natives.add(key)
            import_name = NAME_OVERRIDE.get(name, name)
            lines.append(f'    @Import(name = "{import_name}")')
            lines.append(f"    private static native {PRIM.get(ret, 'int')} n{name}({', '.join(nsig)});")
            lines.append("")

    lines.append(HAND_SECTION)
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{OUT}: {n_gen} generated + {len(HAND_WRITTEN)} hand-written")


def simple(t):
    if t in PRIM:
        return t
    return t.split(".")[-1]


HAND_SECTION = """    /* ---- hand-written: string-returning / char** functions ---- */

    @Override
    public String glGetString(int name) {
        return CStrings.fromC(nglGetString(name));
    }

    @Import(name = "glGetString")
    private static native Address nglGetString(int name);

    @Override
    public void glShaderSource(int shader, String string) {
        byte[] c = CStrings.toC(string);
        nstsvShaderSource(shader, Address.ofData(c));
    }

    @Import(name = "stsv_glShaderSource")
    private static native void nstsvShaderSource(int shader, Address source);

    @Override
    public String glGetShaderInfoLog(int shader) {
        byte[] buf = new byte[4096];
        int[] len = new int[1];
        nglGetShaderInfoLog(shader, buf.length, Address.ofData(len), Address.ofData(buf));
        return new String(buf, 0, len[0]);
    }

    @Import(name = "glGetShaderInfoLog")
    private static native void nglGetShaderInfoLog(int shader, int bufSize, Address length, Address infoLog);

    @Override
    public String glGetProgramInfoLog(int program) {
        byte[] buf = new byte[4096];
        int[] len = new int[1];
        nglGetProgramInfoLog(program, buf.length, Address.ofData(len), Address.ofData(buf));
        return new String(buf, 0, len[0]);
    }

    @Import(name = "glGetProgramInfoLog")
    private static native void nglGetProgramInfoLog(int program, int bufSize, Address length, Address infoLog);

    @Override
    public String glGetActiveAttrib(int program, int index, IntBuffer size, Buffer type) {
        byte[] buf = new byte[256];
        int[] len = new int[1];
        int[] sizeTmp = new int[1];
        int[] typeTmp = new int[1];
        nglGetActiveAttrib(program, index, buf.length, Address.ofData(len),
                Address.ofData(sizeTmp), Address.ofData(typeTmp), Address.ofData(buf));
        putInt(size, sizeTmp[0]);
        putInt(type, typeTmp[0]);
        return new String(buf, 0, len[0]);
    }

    @Import(name = "glGetActiveAttrib")
    private static native void nglGetActiveAttrib(int program, int index, int bufSize,
            Address length, Address size, Address type, Address name);

    @Override
    public String glGetActiveUniform(int program, int index, IntBuffer size, Buffer type) {
        byte[] buf = new byte[256];
        int[] len = new int[1];
        int[] sizeTmp = new int[1];
        int[] typeTmp = new int[1];
        nglGetActiveUniform(program, index, buf.length, Address.ofData(len),
                Address.ofData(sizeTmp), Address.ofData(typeTmp), Address.ofData(buf));
        putInt(size, sizeTmp[0]);
        putInt(type, typeTmp[0]);
        return new String(buf, 0, len[0]);
    }

    @Import(name = "glGetActiveUniform")
    private static native void nglGetActiveUniform(int program, int index, int bufSize,
            Address length, Address size, Address type, Address name);
"""


if __name__ == "__main__":
    emit()
